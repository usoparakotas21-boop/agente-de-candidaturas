-- O aplicativo principal usa a tabela inglesa candidates. O UUID abaixo
-- mantém o mesmo contrato de proprietário sem quebrar owner_id legado.
ALTER TABLE public.candidates ADD COLUMN IF NOT EXISTS user_id UUID;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_candidates_user_id'
          AND conrelid = 'public.candidates'::regclass
    ) THEN
        ALTER TABLE public.candidates
            ADD CONSTRAINT fk_candidates_user_id
            FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE;
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_candidatos_user_id'
          AND conrelid = 'public.candidatos'::regclass
    ) THEN
        ALTER TABLE public.candidatos
            ADD CONSTRAINT fk_candidatos_user_id
            FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE;
    END IF;
END $$;

