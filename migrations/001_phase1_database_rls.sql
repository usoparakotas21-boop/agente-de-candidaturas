-- Autorização administrativa deve usar app_metadata, que o usuário não pode
-- editar. user_metadata não é utilizado para decisões de RLS.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SET search_path = pg_catalog, public, auth
AS $$
    SELECT COALESCE(
        (auth.jwt() -> 'app_metadata' ->> 'is_admin') IN ('true', '1'),
        FALSE
    );
$$;

CREATE OR REPLACE FUNCTION public.trigger_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

-- Defende também tabelas públicas legadas. Tabelas sem política continuam
-- inacessíveis pelo Data API após o RLS ser habilitado.
DO $$
DECLARE
    item RECORD;
BEGIN
    FOR item IN
        SELECT n.nspname AS schema_name, c.relname AS table_name
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public'
          AND c.relkind IN ('r', 'p')
    LOOP
        EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', item.schema_name, item.table_name);
    END LOOP;
END $$;

DO $$
DECLARE
    item RECORD;
BEGIN
    FOR item IN
        SELECT table_name
        FROM information_schema.columns
        WHERE table_schema = 'public' AND column_name = 'updated_at'
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trigger_set_updated_at ON public.%I', item.table_name);
        EXECUTE format(
            'CREATE TRIGGER trigger_set_updated_at BEFORE UPDATE ON public.%I '
            'FOR EACH ROW EXECUTE FUNCTION public.trigger_set_updated_at()',
            item.table_name
        );
    END LOOP;
END $$;

