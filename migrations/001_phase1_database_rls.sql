-- Candidatura Certa - Fase 1: normalização do catálogo e RLS
--
-- Esta migração é aditiva e idempotente. Ela preserva as tabelas legadas
-- usadas pelo aplicativo (candidates, jobs e email_integrations) e cria os
-- contratos em português usados pelo coletor assíncrono. Os tokens das
-- integrações devem ser gravados cifrados; esta tabela nunca deve ser exposta
-- ao navegador.

