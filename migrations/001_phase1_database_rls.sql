-- Tabelas de operação não são uma API de usuário. Políticas deny explícitas
-- documentam esse contrato e mantêm o acesso restrito ao servidor/service_role.
DO $$
DECLARE
    item RECORD;
    policy_name TEXT;
BEGIN
    FOR item IN
        SELECT unnest(ARRAY[
            'admin_audit_logs', 'ebook_purchases', 'expiring_job_email_outbox',
            'interview_email_outbox', 'job_ingestion_runs', 'job_ingestion_tasks',
            'linkedin_rebranding_purchases', 'product_feedback'
        ]) AS table_name
    LOOP
        IF to_regclass(format('public.%I', item.table_name)) IS NOT NULL THEN
            policy_name := item.table_name || '_server_only';
            EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', policy_name, item.table_name);
            EXECUTE format(
                'CREATE POLICY %I ON public.%I FOR ALL TO anon, authenticated USING (FALSE) WITH CHECK (FALSE)',
                policy_name, item.table_name
            );
        END IF;
    END LOOP;
END $$;

